import jsPDF from 'jspdf';
import { UMLModel, UMLClass, Relationship } from '../types/uml';

/**
 * Generates an executive, university-grade Software Engineering PDF Document
 * containing project specs, high-resolution diagram, and class dictionaries.
 */
export async function generateUmlPdf(
  model: UMLModel,
  classDiagramSvgElement?: SVGSVGElement | null,
  useCaseSvgElement?: SVGSVGElement | null
): Promise<void> {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 14;
  let cursorY = 20;

  // Helper: check page break
  const ensureSpace = (neededHeight: number) => {
    if (cursorY + neededHeight > pageHeight - margin) {
      doc.addPage();
      cursorY = 20;
      // Header on subsequent pages
      doc.setFontSize(8);
      doc.setTextColor(140, 140, 140);
      doc.text(`UML Architecture Specification • ${model.systemName}`, margin, 12);
      doc.setDrawColor(220, 220, 220);
      doc.line(margin, 14, pageWidth - margin, 14);
    }
  };

  // Helper: draw SVG to canvas and get data URL
  const svgToDataUrl = async (svgEl: SVGSVGElement): Promise<string> => {
    return new Promise((resolve, reject) => {
      try {
        const clonedSvg = svgEl.cloneNode(true) as SVGSVGElement;
        clonedSvg.setAttribute('dir', 'ltr');
        
        // Remove transform group panning to fit cleanly
        const rootGroup = clonedSvg.querySelector('g');
        if (rootGroup) {
          // Keep current group or reset if desired
        }

        const xml = new XMLSerializer().serializeToString(clonedSvg);
        const svg64 = btoa(unescape(encodeURIComponent(xml)));
        const image64 = `data:image/svg+xml;base64,${svg64}`;

        const img = new Image();
        img.onload = () => {
          const canvas = document.createElement('canvas');
          const scale = 2; // high res
          canvas.width = (img.width || 1200) * scale;
          canvas.height = (img.height || 800) * scale;
          const ctx = canvas.getContext('2d');
          if (ctx) {
            ctx.fillStyle = '#0f172a'; // dark elegant background
            ctx.fillRect(0, 0, canvas.width, canvas.height);
            ctx.drawImage(img, 0, 0, canvas.width, canvas.height);
            resolve(canvas.toDataURL('image/png'));
          } else {
            resolve('');
          }
        };
        img.onerror = () => resolve('');
        img.src = image64;
      } catch (e) {
        resolve('');
      }
    });
  };

  // ==========================================
  // PAGE 1: TITLE & EXECUTIVE SUMMARY
  // ==========================================

  // Header Banner
  doc.setFillColor(15, 23, 42); // slate-900
  doc.rect(0, 0, pageWidth, 42, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(20);
  doc.setFont('helvetica', 'bold');
  doc.text('UML ARCHITECTURE SPECIFICATION', margin, 20);

  doc.setFontSize(11);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(226, 232, 240);
  doc.text(`System: ${model.systemName}`, margin, 28);

  doc.setFontSize(9);
  doc.setTextColor(148, 163, 184);
  doc.text(`Generated by RoseUML AI for IBM Rational Rose • Date: ${new Date().toLocaleDateString()}`, margin, 35);

  cursorY = 52;

  // Overview Box
  doc.setFillColor(248, 250, 252);
  doc.setDrawColor(226, 232, 240);
  doc.roundedRect(margin, cursorY, pageWidth - margin * 2, 28, 3, 3, 'FD');

  doc.setTextColor(30, 41, 59);
  doc.setFontSize(11);
  doc.setFont('helvetica', 'bold');
  doc.text('System Architectural Overview', margin + 5, cursorY + 8);

  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(71, 85, 105);
  const descLines = doc.splitTextToSize(model.description || 'Complete Object-Oriented Software Architecture with Class & Use Case models.', pageWidth - margin * 2 - 10);
  doc.text(descLines, margin + 5, cursorY + 16);

  cursorY += 36;

  // Architecture Metrics Grid (4 Stat Badges)
  const statWidth = (pageWidth - margin * 2 - 9) / 4;
  const stats = [
    { label: 'Total Classes', value: model.classes.length.toString(), color: [225, 29, 72] }, // rose-600
    { label: 'Relationships', value: model.relationships.length.toString(), color: [79, 70, 229] }, // indigo-600
    { label: 'Use Cases', value: model.useCases.length.toString(), color: [13, 148, 136] }, // teal-600
    { label: 'Actors', value: model.actors.length.toString(), color: [217, 119, 6] }, // amber-600
  ];

  stats.forEach((s, idx) => {
    const boxX = margin + idx * (statWidth + 3);
    doc.setFillColor(255, 255, 255);
    doc.setDrawColor(226, 232, 240);
    doc.roundedRect(boxX, cursorY, statWidth, 22, 2, 2, 'FD');

    // Colored accent left border
    doc.setFillColor(s.color[0], s.color[1], s.color[2]);
    doc.rect(boxX, cursorY, 3, 22, 'F');

    doc.setFontSize(16);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(s.color[0], s.color[1], s.color[2]);
    doc.text(s.value, boxX + 8, cursorY + 11);

    doc.setFontSize(8);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(100, 116, 139);
    doc.text(s.label, boxX + 8, cursorY + 18);
  });

  cursorY += 32;

  // Class Diagram Snapshot (if available)
  if (classDiagramSvgElement) {
    try {
      const imgData = await svgToDataUrl(classDiagramSvgElement);
      if (imgData) {
        doc.setFontSize(12);
        doc.setFont('helvetica', 'bold');
        doc.setTextColor(15, 23, 42);
        doc.text('1. Class Diagram Visual Preview', margin, cursorY);
        cursorY += 6;

        const imgHeight = 110;
        doc.setDrawColor(203, 213, 225);
        doc.rect(margin, cursorY, pageWidth - margin * 2, imgHeight, 'S');
        doc.addImage(imgData, 'PNG', margin, cursorY, pageWidth - margin * 2, imgHeight);

        cursorY += imgHeight + 10;
      }
    } catch (e) {
      console.error('Error rendering diagram to PDF:', e);
    }
  }

  // ==========================================
  // PAGE 2+: CLASS SPECIFICATIONS & DICTIONARY
  // ==========================================
  doc.addPage();
  cursorY = 24;

  doc.setFontSize(14);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(15, 23, 42);
  doc.text('2. Class Specifications & Data Dictionary', margin, cursorY);
  cursorY += 8;

  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(100, 116, 139);
  doc.text('Detailed specification of all classes, attributes, visibility modifiers and operations:', margin, cursorY);
  cursorY += 8;

  model.classes.forEach((cls, cIdx) => {
    // Estimate needed box height
    const attrCount = cls.attributes.length;
    const methodCount = cls.methods.length;
    const boxHeight = 22 + Math.max(1, attrCount) * 6 + Math.max(1, methodCount) * 6 + (cls.description ? 8 : 0);

    ensureSpace(boxHeight + 6);

    // Class Box Container
    doc.setFillColor(255, 255, 255);
    doc.setDrawColor(203, 213, 225);
    doc.roundedRect(margin, cursorY, pageWidth - margin * 2, boxHeight, 2, 2, 'FD');

    // Class Header Bar
    doc.setFillColor(241, 245, 249);
    doc.rect(margin, cursorY, pageWidth - margin * 2, 10, 'F');
    doc.line(margin, cursorY + 10, pageWidth - margin * 2, cursorY + 10);

    // Class Name & Stereotype & Persian Name
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10);
    doc.setTextColor(15, 23, 42);
    const stereotypeText = cls.stereotype && cls.stereotype !== 'standard' ? ` <<${cls.stereotype}>>` : '';
    const persianTitle = cls.persianName ? ` [${cls.persianName}]` : '';
    doc.text(`${cIdx + 1}. Class: ${cls.name}${stereotypeText}${persianTitle}`, margin + 4, cursorY + 7);

    let innerY = cursorY + 15;

    // Class Description
    if (cls.description) {
      doc.setFont('helvetica', 'italic');
      doc.setFontSize(8);
      doc.setTextColor(100, 116, 139);
      doc.text(cls.description, margin + 4, innerY);
      innerY += 7;
    }

    // Attributes column header
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8);
    doc.setTextColor(71, 85, 105);
    doc.text('Attributes / Fields:', margin + 4, innerY);
    innerY += 5;

    doc.setFont('courier', 'normal');
    doc.setFontSize(8);
    if (cls.attributes.length === 0) {
      doc.setTextColor(148, 163, 184);
      doc.text('(none)', margin + 8, innerY);
      innerY += 5;
    } else {
      cls.attributes.forEach((attr) => {
        const visSym = attr.visibility === 'public' ? '+' : attr.visibility === 'protected' ? '#' : '-';
        doc.setTextColor(attr.visibility === 'public' ? 22 : attr.visibility === 'protected' ? 180 : 220, 100, 70);
        doc.text(`${visSym} ${attr.name}: ${attr.type}`, margin + 8, innerY);
        innerY += 5;
      });
    }

    innerY += 2;

    // Methods column header
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8);
    doc.setTextColor(71, 85, 105);
    doc.text('Operations / Methods:', margin + 4, innerY);
    innerY += 5;

    doc.setFont('courier', 'normal');
    doc.setFontSize(8);
    if (cls.methods.length === 0) {
      doc.setTextColor(148, 163, 184);
      doc.text('(none)', margin + 8, innerY);
      innerY += 5;
    } else {
      cls.methods.forEach((m) => {
        const visSym = m.visibility === 'public' ? '+' : m.visibility === 'protected' ? '#' : '-';
        const params = m.parameters.map((p) => `${p.name}: ${p.type}`).join(', ');
        doc.setTextColor(30, 41, 59);
        doc.text(`${visSym} ${m.name}(${params}): ${m.returnType}`, margin + 8, innerY);
        innerY += 5;
      });
    }

    cursorY += boxHeight + 6;
  });

  // ==========================================
  // RELATIONSHIPS TABLE
  // ==========================================
  ensureSpace(40);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(15, 23, 42);
  doc.text('3. UML Relationship Matrix', margin, cursorY);
  cursorY += 6;

  // Table Header
  const colWidths = [45, 35, 45, 25, 30];
  const tableHeaders = ['Source Class', 'Relation Type', 'Target Class', 'Multiplicity', 'Semantic Label'];
  doc.setFillColor(241, 245, 249);
  doc.rect(margin, cursorY, pageWidth - margin * 2, 8, 'F');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8);
  doc.setTextColor(71, 85, 105);

  let headerX = margin + 2;
  tableHeaders.forEach((h, i) => {
    doc.text(h, headerX, cursorY + 5.5);
    headerX += colWidths[i];
  });
  cursorY += 8;

  // Table Rows
  model.relationships.forEach((rel, rIdx) => {
    ensureSpace(8);
    if (rIdx % 2 === 1) {
      doc.setFillColor(248, 250, 252);
      doc.rect(margin, cursorY, pageWidth - margin * 2, 7, 'F');
    }

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(30, 41, 59);

    let rowX = margin + 2;
    doc.text(rel.source, rowX, cursorY + 5);
    rowX += colWidths[0];

    // Colored relation badge
    doc.setFont('helvetica', 'bold');
    if (rel.type === 'inheritance') doc.setTextColor(2, 132, 199);
    else if (rel.type === 'composition') doc.setTextColor(225, 29, 72);
    else if (rel.type === 'aggregation') doc.setTextColor(217, 119, 6);
    else doc.setTextColor(79, 70, 229);
    doc.text(rel.type, rowX, cursorY + 5);
    rowX += colWidths[1];

    doc.setFont('helvetica', 'normal');
    doc.setTextColor(30, 41, 59);
    doc.text(rel.target, rowX, cursorY + 5);
    rowX += colWidths[2];

    const mult = `${rel.sourceMultiplicity || '1'} : ${rel.targetMultiplicity || '1'}`;
    doc.text(mult, rowX, cursorY + 5);
    rowX += colWidths[3];

    doc.text(rel.label || '-', rowX, cursorY + 5);

    cursorY += 7;
  });

  cursorY += 10;

  // ==========================================
  // RATIONAL ROSE EXECUTION GUIDE (PAGE END)
  // ==========================================
  ensureSpace(40);
  doc.setFillColor(240, 253, 250); // teal-50
  doc.setDrawColor(153, 246, 228);
  doc.roundedRect(margin, cursorY, pageWidth - margin * 2, 32, 2, 2, 'FD');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.setTextColor(15, 118, 110);
  doc.text('IBM Rational Rose Import & Execution Guide', margin + 5, cursorY + 7);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(19, 78, 74);
  doc.text('1. Open Rational Rose -> Tools -> Open Script... -> select the generated .ebs file.', margin + 5, cursorY + 14);
  doc.text('2. Press F5 (Run) to automatically build classes, attributes, operations, and diagrams.', margin + 5, cursorY + 20);
  doc.text('3. Or use File -> Open to load the generated .mdl native model directly into Rose.', margin + 5, cursorY + 26);

  // Save PDF
  const filename = `${model.systemName.replace(/[^a-zA-Z0-9]/g, '_')}_UML_Specification.pdf`;
  doc.save(filename);
}
